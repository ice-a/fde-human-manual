const dir = new URL('../src/data/content/', import.meta.url)

for (const [slug, sections] of Object.entries(additions)) {
  const file = new URL(`${slug}.zh-CN.json`, dir)
  const payload = JSON.parse(await readFile(file, 'utf8')) as {
    slug: string
    sections: { title: string; items: unknown[] }[]
  }

  sections.forEach((rows, index) => {
    const section = payload.sections[index]
    if (!section) throw new Error(`${slug} section ${index} missing`)
    rows.forEach(([title, core, points, tags], itemIndex) => {
      section.items.push({
        id: `${slug}-${index}-${section.items.length + 1}`,
        title,
        core,
        body: points,
        tags,
      })
    })
  })

  await writeFile(file, `${JSON.stringify(payload, null, 2)}\n`, 'utf8')
  process.stdout.write(`${slug}: ${payload.sections.reduce((sum, s) => sum + s.items.length, 0)} items\n`)
}
