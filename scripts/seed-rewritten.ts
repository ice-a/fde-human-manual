async function build(slug: string, sourceUrl: string, groups: { title: string; rows: Row[] }[]) {
  const sections = groups.map((group, sectionIndex) => ({
    title: group.title,
    items: group.rows.map(([title, core, points, tags], index) => ({
      id: `${slug}-${sectionIndex}-${index + 1}`,
      title,
      core,
      body: points,
      tags,
      sourceUrl,
    })),
  }))
  const dir = new URL('../src/data/content/', import.meta.url)
  await mkdir(dir, { recursive: true })
  await writeFile(
    new URL(`${slug}.zh-CN.json`, dir),
    `${JSON.stringify({ slug, sections }, null, 2)}\n`,
    'utf8',
  )
  process.stdout.write(`${slug}: ${sections.reduce((sum, s) => sum + s.items.length, 0)} items\n`)
}

