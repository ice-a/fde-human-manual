async function build(entry: (typeof groups)[number]) {
  const sections = entry.sections.map((section, sectionIndex) => ({
    title: section.title,
    items: section.rows.map(([title, core, points, tags], index) => ({
      id: `${entry.slug}-${sectionIndex}-${index + 1}`,
      title,
      core,
      body: points,
      tags,
    })),
  }))
  const dir = new URL('../src/data/content/', import.meta.url)
  await mkdir(dir, { recursive: true })
  await writeFile(
    new URL(`${entry.slug}.zh-CN.json`, dir),
    `${JSON.stringify({ slug: entry.slug, sections }, null, 2)}\n`,
    'utf8',
  )
  process.stdout.write(`${entry.slug}: ${sections.reduce((sum, s) => sum + s.items.length, 0)} items\n`)
}

for (const entry of groups) await build(entry)
